# ==================== معالجة واجهة تسجيل الأطفال ====================
def render_child_form():
    form_data = {}
    
    for col_name in CHILD_COLUMNS:
        # الحقول الخاصة بالتطور (المجموعة الأولى)
        if col_name in ["النمو والتطور الحركى", "التطور الادراكى والمعرفى", "التطور اللغوى"]:
            options = ["طبيعى", "متقدم", "متاخر"]
            # افتراضي "طبيعى"
            current_val = st.session_state.get(f"c_{col_name}", "طبيعى")
            form_data[col_name] = st.selectbox(f"{col_name} (افتراضي: طبيعى)", options, index=options.index(current_val), key=f"c_{col_name}")

        # الحقول الخاصة بالرسائل والتوعية (المجموعة الثانية)
        elif col_name in ["رسائل التربية الايجابية", "الانشطة التحفيزية", "التوعية عن التغذية التكميلية وسلامة الغذاء"]:
            options = ["تم", "لم يتم"]
            # افتراضي "تم"
            current_val = st.session_state.get(f"c_{col_name}", "تم")
            form_data[col_name] = st.selectbox(f"{col_name} (افتراضي: تم)", options, index=options.index(current_val), key=f"c_{col_name}")
            
        # باقي الحقول التقليدية
        else:
            if col_name in ["تاريخ التسجيل", "اسم المستخدم"]: continue
            form_data[col_name] = st.text_input(col_name, key=f"c_{col_name}")
            
    return form_data

