def clean_digits(val, max_len=None):
  if not val: return ""
  digits = "".join(filter(str.isdigit, str(val)))
  return digits[:max_len] if max_len else digits

def parse_national_id(nat_id):
  clean_id = clean_digits(nat_id, 14)
  if len(clean_id) == 14:
    century = 2000 if int(clean_id[0]) == 3 else 1900
    birth_date = datetime.date(century + int(clean_id[1:3]), int(clean_id[3:5]), int(clean_id[5:7]))
    age = datetime.date.today().year - birth_date.year - ((datetime.date.today().month, datetime.date.today().day) < (birth_date.month, birth_date.day))
    return str(birth_date), str(age)
  return "", ""

def get_existing_data(nat_id, sheet_name, id_column):
  clean_id = clean_digits(nat_id, 14)
  if os.path.exists(EXCEL_FILE) and len(clean_id) == 14:
    try:
      df = pd.read_excel(EXCEL_FILE, sheet_name=sheet_name, dtype=str)
      match = df[df[id_column].str.strip() == clean_id]
      return match.iloc[-1].to_dict() if not match.empty else {}
    except: pass
  return {}

